from __future__ import annotations

import os
from typing import Callable, Dict, Optional, Sequence

import numpy as np
import pandas as pd

TABLEDIR = "tables"

# Column formatting: how many decimals, and which direction is better.
FORMATS = {
    "W2": ("{:.4f}", "lower"), "F": ("{:.3e}", "lower"), "H": ("{:.4f}", "lower"),
    "MMD2": ("{:.3e}", "lower"), "Vnorm": ("{:.4f}", "lower"),
    "mass_err": ("{:.4f}", "lower"), "n_covered": ("{:.0f}", "higher"),
    "entropy": ("{:.3f}", "higher"), "precision": ("{:.3f}", "higher"),
    "beta_F": ("{:.3f}", "higher"), "beta_star": ("{:.3f}", "higher"),
    "rate_W2": ("{:.2e}", "higher"), "k_all_modes": ("{:.0f}", "lower"),
    "alpha_hat": ("{:.3f}", "higher"), "L_hat": ("{:.3f}", "lower"),
}

PRETTY = {
    "W2": r"$W_2(q^K,p)$", "F": r"$\mathcal{F}(q^K)$", "H": r"$\mathrm{KL}(q_\sigma\|p_\sigma)$",
    "MMD2": r"$\mathrm{MMD}^2_k$", "Vnorm": r"$\|V\|_{L^2(q)}$",
    "n_covered": "modes", "entropy": r"$H_{\rm cov}$", "precision": "prec.",
    "mass_err": r"$\|m(q)-w_p\|_1$", "beta_F": r"$\beta_{\mathcal{F}}$",
    "beta_star": r"$\beta_\star$", "rate_W2": r"rate of $W_2$",
    "k_all_modes": r"$k_{\rm all}$", "pct_KM_ok": r"\% KM ok",
    "alpha_hat": r"$\hat\alpha$", "L_hat": r"$\hat L$",
}


def pct_above(values, threshold: float) -> float:
    """Percentage of *defined* entries that are >= threshold.

    NaNs mark steps where the certificate is 0/0 (a converged state), and a
    plain `mean(v >= t)` would silently count them as failures.
    """
    v = np.asarray(values, dtype=float)
    m = ~np.isnan(v)
    return 100.0 * float((v[m] >= threshold).mean()) if m.any() else np.nan


def pct_below(values, threshold: float) -> float:
    """Percentage of *defined* entries that are < threshold."""
    v = np.asarray(values, dtype=float)
    m = ~np.isnan(v)
    return 100.0 * float((v[m] < threshold).mean()) if m.any() else np.nan


def runs_table(runs: Dict[str, object],
               columns: Sequence[str] = ("W2", "F", "H", "n_covered", "entropy", "precision"),
               n_modes: Optional[int] = None, tau: Optional[float] = None,
               extra: Optional[Callable] = None) -> pd.DataFrame:
    """Final metrics of a batch of runs, one row per run."""
    rows = {}
    for key, r in runs.items():
        row = {"run": r.label}
        row.update({c: r.final(c) for c in columns if c in r.probes})
        if "W2" in r.probes:
            row["rate_W2"] = r.rate("W2")
        if n_modes is not None and "n_covered" in r.probes:
            row["k_all_modes"] = r.first_k_where("n_covered", lambda v: v >= n_modes)
        if tau is not None and "beta_star" in r.probes:
            row["pct_KM_ok"] = pct_above(r.probes["beta_star"], tau / 2)
        if tau is not None and "beta_F" in r.probes:
            row["pct_beta_F_ge_tau_over_2"] = pct_above(r.probes["beta_F"], tau / 2)
        if extra is not None:
            row.update(extra(r))
        rows[key] = row
    return pd.DataFrame.from_dict(rows, orient="index").rename_axis("key")


def style(df: pd.DataFrame, highlight: bool = True):
    """Format numbers per column and bold the best cell (for notebook display)."""
    out = df.copy()
    styler = out.style.format({c: FORMATS[c][0] for c in out.columns if c in FORMATS},
                              na_rep="—")
    if highlight:
        for c in out.columns:
            if c in FORMATS and pd.api.types.is_numeric_dtype(out[c]):
                fn = "highlight_min" if FORMATS[c][1] == "lower" else "highlight_max"
                styler = getattr(styler, fn)(subset=[c], props="font-weight:bold;")
    return styler


def save_table(df: pd.DataFrame, name: str, caption: str = "", label: str = "",
               subdir: str = TABLEDIR, float_format: str = "%.4f") -> dict:
    """Write `name.csv` and `name.tex` (booktabs) and return both paths."""
    os.makedirs(subdir, exist_ok=True)
    csv_path = os.path.join(subdir, f"{name}.csv")
    tex_path = os.path.join(subdir, f"{name}.tex")
    df.to_csv(csv_path)

    pretty = df.rename(columns=PRETTY)
    tex = pretty.to_latex(index=True, escape=False, float_format=float_format,
                          caption=caption or name,
                          label=label or f"tab:{name}", position="H")
    # booktabs is already what to_latex emits; just make it self-contained
    with open(tex_path, "w") as f:
        f.write("% generated by msflow.report.save_table -- do not edit by hand\n")
        f.write(tex)
    return dict(csv=csv_path, tex=tex_path)


def checks_table(results: Sequence[dict]) -> pd.DataFrame:
    """Format the output of `msflow.checks.run_all` as a pass/fail table."""
    df = pd.DataFrame(results)
    df["status"] = np.where(df["passed"], "PASS", "FAIL")
    cols = ["check", "status", "error", "tolerance", "detail"]
    return df[[c for c in cols if c in df.columns]].set_index("check")
